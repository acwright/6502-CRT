#!/usr/bin/env node
// Generate the banked cartridge linker configs.
//
// Four targets, 15 to 127 bank segments each. Writing that many near-identical
// stanzas by hand is how they drift, so they are generated — and committed, so
// they can be read, diffed and copied into 6502-ASM and 6502-C the way 6502.inc
// already is.
//
//   node tools/make-cart-cfg.mjs            rewrite all four
//   node tools/make-cart-cfg.mjs --check    exit 1 if any is stale
//
// The layout is 6502-CRT PLAN.md §2, over the mapper of 6502-VCS PLAN.md §2.
// ld65 writes each MEMORY area that names a file to that file **in declaration
// order**, which is exactly the flash's linear layout, so a config is: every
// switchable bank in order, then the fixed bank, then the vectors — and for a
// -1M cart, U2's banks after those, because U2 is the second half of the file.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const BANK_SIZE = 0x2000

/**
 * The four flash cart targets of 6502-VCS PLAN.md §1.
 *
 * `banks` is the number of 8 KB banks on the primary chip; the last of them is
 * the fixed bank and is never switchable. `chips` is 1, or 2 for a -1M cart.
 */
const TARGETS = [
  { target: '128K', bytes: 0x020000, part: 'SST39SF010A', chips: 1 },
  { target: '256K', bytes: 0x040000, part: 'SST39SF020A', chips: 1 },
  { target: '512K', bytes: 0x080000, part: 'SST39SF040', chips: 1 },
  { target: '1M', bytes: 0x100000, part: 'SST39SF040 x2', chips: 2 }
]

const hex2 = (n) => n.toString(16).toUpperCase().padStart(2, '0')

/** The bank values a cart may write to the register, in file order. */
function banksFor({ bytes, chips }) {
  const chipSize = bytes / chips
  const perChip = chipSize / BANK_SIZE
  const fixed = perChip - 1 // the primary chip's last 8 KB
  const primary = [...Array(fixed).keys()] // 0 .. fixed-1
  // B6 selects U2, so its banks are $40 upwards. They come after FIXED and
  // VECTORS in the file, because U2 is the file's second half.
  const secondary = chips === 2 ? [...Array(perChip).keys()].map((b) => 0x40 | b) : []
  return { fixed, primary, secondary }
}

function generate(spec) {
  const { target, bytes, part, chips } = spec
  const { fixed, primary, secondary } = banksFor(spec)
  const area = (name, start, size, comment) =>
    `  ${(name + ':').padEnd(9)}start=$${start.toString(16).toUpperCase().padStart(4, '0')}, ` +
    `size=$${size.toString(16).toUpperCase().padStart(4, '0')}, file="%O", fill=yes, fillval=$FF;` +
    (comment ? `  # ${comment}` : '')

  const memory = [
    ...primary.map((b, i) =>
      area(
        `BANK${hex2(b)}`,
        0xC000,
        BANK_SIZE,
        i === 0 ? 'the switchable window, $C000-$DFFF' : ''
      )
    ),
    area('FIXED', 0xE000, 0x1FFA, `always visible, whatever the register holds (bank $${hex2(fixed)})`),
    area('VECTORS', 0xFFFA, 0x0006, 'NMI, RESET, IRQ — never bankable'),
    ...secondary.map((b, i) =>
      area(`BANK${hex2(b)}`, 0xC000, BANK_SIZE, i === 0 ? 'U2, the file’s second half' : '')
    )
  ]

  const segment = (name, optional) =>
    `  ${(name + ':').padEnd(9)}load=${(name + ',').padEnd(9)}type=ro${optional ? ', optional=yes' : ''};`

  const segments = [
    ...primary.map((b) => segment(`BANK${hex2(b)}`, true)),
    segment('FIXED', false),
    segment('VECTORS', false),
    ...secondary.map((b) => segment(`BANK${hex2(b)}`, true))
  ]

  const usable = [...primary, ...secondary]
  const usableText =
    chips === 2
      ? `$00-$${hex2(fixed - 1)} and $40-$7F`
      : `$00-$${hex2(fixed - 1)}`

  return `# ***                          ***
# ***     6502 ${target.padEnd(4)} CONFIG      ***
# ***                          ***
#
#   A banked cartridge for the AC6502 Flash Cart: ${part}, ${bytes.toLocaleString()} bytes.
#   Generated by tools/make-cart-cfg.mjs — do not edit. \`--check\` fails on a
#   stale copy.
#
#   THE MAPPER (6502-VCS PLAN.md §2)
#   --------------------------------
#   $C000-$DFFF  8 KB switchable window. Which bank appears here is the value
#                last written to the bank register.
#   $E000-$FFFF  8 KB fixed region — the primary chip's last 8 KB, always, and
#                the only place the reset and interrupt vectors can live.
#
#   The bank register is write-only at ANY address in $E000-$FFFF (\`BANK\` in
#   Cart.asm is $E000 by convention), it cannot be read back, and RESB clears it
#   to 0. **A write there latches the register and reaches no flash.**
#
#   THE SEGMENT NAME IS THE VALUE YOU WRITE
#   ---------------------------------------
#   \`.segment "BANK07"\` is reached with \`lda #$07\` / \`jsr SetBank\`.
#   Usable bank values here: ${usableText} (${usable.length} banks, ${(usable.length * BANK_SIZE / 1024)} KB).
#   $${hex2(fixed)} is the fixed bank and has no BANK segment: it is FIXED.
#
#   WHY fillval=$FF
#   ---------------
#   $FF is what an erased flash chip holds, so every unused byte already matches
#   the chip after a chip erase and \`6502-flash program\` skips the sector
#   outright. A small cart in a big image programs in seconds instead of a
#   minute and a half. The legacy 6502.cfg keeps fillval=$00 — an EEPROM has no
#   erased state to exploit.
#
#   WHY THE DECLARATION ORDER MATTERS
#   ---------------------------------
#   ld65 writes each MEMORY area that names a file to that file in the order the
#   areas are declared, and that order IS the flash's linear layout. Do not
#   reorder these blocks.
#
#   See the 6502-DOCS chapter *Bigger cartridges*, and 6502-CRT's README section
#   *Building for the Flash Cart*.

MEMORY {
${memory.join('\n')}
}

SEGMENTS {
${segments.join('\n')}
}
`
}

const files = TARGETS.map((spec) => ({
  name: `6502-${spec.target}.cfg`,
  text: generate(spec),
  bytes: spec.bytes
}))

// The size each config must produce is arithmetic, not a promise: assert it
// here so a bad table is caught before ld65 quietly emits a short file.
for (const spec of TARGETS) {
  const { primary, secondary } = banksFor(spec)
  const total = (primary.length + secondary.length + 1) * BANK_SIZE
  if (total !== spec.bytes) {
    console.error(`${spec.target}: banks total ${total} bytes, expected ${spec.bytes}`)
    process.exit(1)
  }
}

const check = process.argv.includes('--check')
let stale = 0

for (const file of files) {
  const path = join(ROOT, file.name)
  if (check) {
    let current = null
    try {
      current = readFileSync(path, 'utf8')
    } catch {
      /* missing counts as stale */
    }
    if (current !== file.text) {
      console.error(`${file.name} is stale`)
      stale++
    }
  } else {
    writeFileSync(path, file.text)
    console.log(`${file.name}  ${file.bytes.toLocaleString()} bytes when linked`)
  }
}

if (check) {
  if (stale) {
    console.error('Run `node tools/make-cart-cfg.mjs` to regenerate.')
    process.exit(1)
  }
  console.log('All four cartridge configs are up to date.')
}
